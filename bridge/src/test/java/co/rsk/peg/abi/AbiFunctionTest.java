    private static String describe(Object[] values) {
        StringBuilder sb = new StringBuilder();
        for (Object v : values) {
            sb.append(describe(v)).append(';');
        }
        return sb.toString();
    }

    /** The same rendering the recording used, with a Besu address shown as RSKj's 32-byte word. */
    private static String describe(Object v) {
        if (v instanceof byte[] bytes) {
            return "bytes:" + Bytes.wrap(bytes).toUnprefixedHexString();
        }
        if (v instanceof BigInteger) {
            return "bigint:" + v;
        }
        if (v instanceof String) {
            return "string:" + v;
        }
        if (v instanceof Boolean) {
            return "bool:" + v;
        }
        if (v instanceof Address address) {
            return "dataword:" + "0".repeat(24) + address.getBytes().toUnprefixedHexString();
        }
        if (v instanceof Object[] array) {
            StringBuilder sb = new StringBuilder("array[");
            for (Object e : array) {
                sb.append(describe(e)).append('|');
            }
            return sb.append(']').toString();
        }
        return v.getClass().getSimpleName() + ":" + v;
    }

    private static byte[] bytes(int first, int length) {
        byte[] b = new byte[length];
        for (int i = 0; i < length; i++) {
            b[i] = (byte) (first + i);
        }
        return b;
    }

    private static Map<String, String> parse(String recorded) {
        Map<String, String> values = new HashMap<>();
        for (String line : recorded.split("\n")) {
            if (line.isBlank()) {
                continue;
            }
            int separator = line.indexOf('=');
            values.put(line.substring(0, separator), line.substring(separator + 1));
        }
        assertTrue(values.size() > 250, "recorded vectors");
        return values;
    }
