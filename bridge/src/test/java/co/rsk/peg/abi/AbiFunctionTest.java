    @Test
    void everyBridgeEventEncodesTopicsAndDataAsRskj() {
        for (BridgeEvents event : BridgeEvents.values()) {
            AbiFunction function = event.getEvent();
            List<Object> indexed = new ArrayList<>();
            List<Object> data = new ArrayList<>();
            for (AbiFunction.Param param : function.getInputs()) {
                (param.indexed() ? indexed : data).add(sample(param.type()));
            }
            StringBuilder topics = new StringBuilder();
            for (LogTopic topic : function.encodeEventTopics(indexed.toArray())) {
                topics.append(topic.getBytes().toUnprefixedHexString()).append(',');
            }
            assertEquals(RSKJ.get("event." + event.name() + ".topics"), topics.toString(), event.name());
            assertEquals(RSKJ.get("event." + event.name() + ".data"), function.encodeEventData(data.toArray()).toUnprefixedHexString(), event.name());
        }
    }

