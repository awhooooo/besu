    // Where the adapter differs from RSKj's codec

    @Test
    void emptyDynamicValuesFollowTheAbiSpecification() {
        // RSKj's codec padded an empty bytes or string to a whole zero word after its zero length; the ABI
        // specification, web3j and every other encoder emit nothing after the length. Both forms decode to the
        // same empty value, here as in RSKj. No bridge event carries an empty dynamic field; only a few results
        // can be empty, and their callers decode them.
        for (String type : new String[]{"bytes", "string"}) {
            String key = "input." + type + ".empty";
            Object empty = type.equals("bytes") ? new byte[0] : "";
            AbiFunction function = AbiFunction.fromSignature("f", new String[]{type}, NO_TYPES);
            Bytes rskjForm = Bytes.fromHexString(RSKJ.get(key + ".encoded"));
            Bytes specForm = function.encode(empty);

            assertEquals(4 + 96, rskjForm.size());
            assertEquals(4 + 64, specForm.size());
            assertEquals(rskjForm.slice(0, specForm.size()), specForm);
            assertEquals(RSKJ.get(key + ".decoded"), describe(function.decode(rskjForm)));
            assertEquals(RSKJ.get(key + ".decoded"), describe(function.decode(specForm)));
        }
    }

